import puppeteer from "puppeteer-core";
const BASE=process.env.ED16_URL||"http://127.0.0.1:50199/";
const b=await puppeteer.launch({executablePath:"/usr/bin/google-chrome-stable",headless:"new",userDataDir:"/tmp/ed16-profiles/comb-"+Date.now(),args:["--no-sandbox","--disable-gpu","--mute-audio"]});
const p=await b.newPage(); const errs=[]; p.on("pageerror",e=>errs.push(e.message)); p.on("dialog",d=>d.accept().catch(()=>{}));
await p.goto(BASE+"?t="+Date.now()); await p.waitForFunction(()=>!!(window.__ED16_PRIS&&window.__ED16_PRIS.combineRules));
const N=60; const r=await p.evaluate((n)=>window.__ED16_PRIS.combineRules(n),N);
console.log(JSON.stringify(r,null,1));
let pass=0,fail=0; const ok=(c,m)=>{ if(c){pass++;console.log("PASS",m);} else {fail++;console.log("FAIL",m);} };
const R=r.res;
ok(R.petMixed.newType===N, "mixed Prismatic pets -> always a type none of the inputs had ("+R.petMixed.newType+"/"+N+")");
ok(R.petMixed.hasUlt===N, "combined Prismatic pet always has an ultimate");
ok((R.petMixed.ultChanged||0)>=N*0.9, "mixed pets: ultimate re-rolled ("+R.petMixed.ultChanged+"/"+N+" differ from inputs' shared ult)");
ok((R.petMixed.abiOrRareDiffers||0)>=N*0.5, "mixed pets: fresh ability/rare (differs from primary in "+R.petMixed.abiOrRareDiffers+"/"+N+")");
ok(R.petSame.keptType===N && R.petSame.keptPrimaryUlt===N, "3 same-type pets keep the type and the primary's ult");
ok(R.wepMixed.hasUlt===N && R.wepMixed.ultChanged>=N*0.9, "mixed weapons roll a new ult ("+R.wepMixed.ultChanged+"/"+N+")");
ok(R.wepSame.keptPrimaryUlt===N, "3 same-kind weapons keep the primary's ult");
ok(R.armorMixed.hasUlt===N && R.armorMixed.ultChanged>=N*0.9, "armor of mixed base rolls a new ult ("+R.armorMixed.ultChanged+"/"+N+")");
ok(R.armorSame.keptPrimaryUlt===N, "3 same-base armor keep the primary's ult");
ok(r.retro.v1!==null && r.retro.v1===r.retro.v2 && r.retro.packed===r.retro.v1, "old Prismatic pet gets a stable ult on load and it survives pack/unpack ("+r.retro.v1+")");
ok(r.retro.lowPet===null, "non-Prismatic pet carries no ult");
ok(r.ults.eq7.includes("pet") && r.ults.eq7.length===7, "ultsOf includes the Prismatic pet (7 buttons)");
ok(!r.ults.withShield.includes("lh"), "shields still excluded");
ok(r.para.seven && r.para.seven.length===6 && !r.para.seven.includes("pet"), "7 ults: Paramount uses the six gear slots");
ok(r.para.fivePlusPet && r.para.fivePlusPet.includes("pet") && r.para.fivePlusPet.length===6, "5 gear ults + Prismatic pet unlocks Paramount");
ok(r.para.fiveNoPet===null, "5 gear ults, no pet: Paramount locked");
ok(errs.length===0,"no page errors "+errs.join(";"));
console.log(`${pass}/${pass+fail} passed`); await b.close();
